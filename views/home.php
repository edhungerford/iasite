    <div class="heading"><h2>STORY</h2></div>
    <p><i>IA IA IA</i> is the story of a duck journeying to a new world. It is also the story of two rabbit knights, one
        very big dragon, a government cover-up, robots, Matryoshka dolls, a village of Komodo dragons, the production of
        leather, toys that come to life, and a thieving magpie (no relation).</p>
    <p><i>IA IA IA</i> is a story about the end of the world.</p>
