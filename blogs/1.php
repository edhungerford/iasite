<p>IA is a word without [known] meaning (although it is said that it can be understood by children and perhaps ducks). Repeated twice, it becomes an insistence. It's counterintuitive to say, but a word without clear meaning can easily come to mean more than the average word.</p>
<ul>
    <li>"I.A." can stand for <i>inter alia</i>, "among other things."</li>
    <li>"Ia" can be the romanized version of the Japanese word for "no."</li>
    <li>Contrarily, "Iá" is a river in Brazil, which is not at all close to denial (a river in Egypt).</li>
</ul>
<p>The Ministry of Travel generally declines to respond to nonsense words. For this reason, a duck may find it difficult to get papers.</p>       
